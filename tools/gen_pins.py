#!/usr/bin/env python3
"""Generate pin constraints, HDL parameters and docs for a part on a board.

One source of truth: tools/partdb.yaml says what the socket signals are,
tools/boardmap.yaml says which AG32 pin each socket pin lands on, and this
turns the pair into everything downstream. Nothing is hand-maintained, so a
part and a board cannot drift out of agreement.

Outputs:
  <out>/<part>.pcf     open-flow pin constraints (agamemnon / nextpnr)
  <out>/<part>.ve      vendor Supra pin constraints
  <out>/<part>_params.vh  HDL parameters for fastprom_top
  docs/04-board-mapping.md  the mapping table, when --docs is given

With --dfu-ve (no --part): <out>/dfu_usb.ve only, the DFU stage's own
USB-only fabric (tools/ag32/build_dfu_fabric.sh): the clocks and USB0, no
pin at all, so the socket and the buffer enable are never driven in DFU mode.
"""
import argparse
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(name):
    with open(os.path.join(ROOT, "tools", name)) as fh:
        return yaml.safe_load(fh)


def check(part_name, part, board_name, board):
    """Refuse to generate a mapping the board cannot physically support."""
    problems = []

    if part_name not in board.get("supports", []):
        problems.append(
            f"board {board_name} does not list {part_name} as supported")

    ins = set(board["input_group"])
    outs = set(board["output_group"])

    for pin, sig in part["socket_pins"].items():
        if sig in ("VCC", "GND"):
            want = board["power"]["vcc"] if sig == "VCC" else board["power"]["gnd"]
            if pin != want:
                problems.append(
                    f"pin {pin} is {sig} on {part_name} but the board puts "
                    f"{sig} on pin {want}")
            continue

        if sig.startswith("D"):
            if pin not in outs:
                problems.append(
                    f"pin {pin} is data line {sig} on {part_name}, but the "
                    f"board drives that pin as an input")
        else:
            if pin not in ins:
                problems.append(
                    f"pin {pin} is {sig} on {part_name}, but the board uses "
                    f"that pin as an output")

    return problems


def fabric_port(sig):
    """Map a socket signal name to the fabric top-level port bit."""
    if sig.startswith("nCE") or sig.startswith("CE"):
        idx = int(sig.lstrip("nCE") or 0)
        return f"ce_pin[{idx}]"
    if sig.startswith("A"):
        return f"a_pin[{int(sig[1:])}]"
    if sig.startswith("D"):
        return f"d_pin[{int(sig[1:])}]"
    raise ValueError(f"unexpected signal {sig}")


def ve_clocks(board):
    """The .ve's clock lines, shared by the ROM's fabric and the DFU stage's.

    The PLL is part of the fabric configuration, so both must configure it
    the same way: the firmware's clock code assumes SYSCLK 100
    (fastprom-hal regs::hz::PLL) whichever fabric is loaded.
    """
    lines = ["SYSCLK 100", "BUSCLK 50"]
    hse_pin = board["control"].get("hse_in")
    if hse_pin:
        # OSC_IN in HSE-bypass mode; the MCU's clock tree, not a fabric pad.
        lines.append(f"HSECLK {board.get('hse_mhz', 12)}   # {hse_pin} (OSC_IN)")
    return lines


def write_dfu_ve(bm, board_name, outdir):
    """The DFU stage's fabric: clocks and USB0, and nothing else.

    No pin line at all: with no port, there is nothing Supra could place on
    an arbitrary pin, and every package pin but OSC_IN and USB's stays an
    unused, undriven pad (tools/ag32/check_dfu_fabric.py proves it from
    Supra's report). In particular the socket's data pins stay
    high-impedance and the buffer enable is left to its pull-up (R21), so the
    bus buffers are off for as long as DFU mode runs.
    """
    if board_name not in bm["boards"]:
        sys.exit(f"unknown board {board_name}; have {', '.join(bm['boards'])}")
    board = bm["boards"][board_name]
    if not board.get("usb"):
        sys.exit(f"board {board_name} has no USB: no DFU fabric for it")
    ve = [f"# DFU stage's USB-only fabric on {board_name} - generated by tools/gen_pins.py --dfu-ve",
          "# vendor Supra constraints: clocks and USB0, no pins",
          ""]
    ve += ve_clocks(board)
    ve.append("USB0 device   # PIN_22/23, PLL output 1 at 60 MHz")
    os.makedirs(outdir, exist_ok=True)
    path = os.path.join(outdir, "dfu_usb.ve")
    with open(path, "w") as fh:
        fh.write("\n".join(ve) + "\n")
    print(f"DFU fabric on {board_name}: clocks and USB0 only")
    print(f"  wrote {os.path.relpath(path, ROOT)}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--part")
    ap.add_argument("--dfu-ve", action="store_true",
                    help="write only <out>/dfu_usb.ve, the DFU stage's USB-only fabric")
    ap.add_argument("--board", default="fastprom-upper")
    ap.add_argument("--open-collector", action="store_true",
                    help="target an open-collector part rather than tri-state")
    ap.add_argument("--banks", type=int, default=0,
                    help="fabric bank-address bits, BANKW (0 = single image)")
    ap.add_argument("--rdclk", type=float, default=200,
                    help="BRAM read-port clock in MHz, from its own PLL output "
                         "(PLLCLK2); 0 clocks the read port from sys_clock")
    ap.add_argument("--out", default="gen")
    ap.add_argument("--docs", action="store_true",
                    help="also write docs/04-board-mapping.md")
    args = ap.parse_args()

    db = load("partdb.yaml")
    bm = load("boardmap.yaml")

    if args.dfu_ve:
        write_dfu_ve(bm, args.board, os.path.join(ROOT, args.out))
        return
    if not args.part:
        ap.error("--part is required (except with --dfu-ve)")
    if args.part not in db["parts"]:
        sys.exit(f"unknown part {args.part}; have {', '.join(db['parts'])}")
    if args.board not in bm["boards"]:
        sys.exit(f"unknown board {args.board}; have {', '.join(bm['boards'])}")

    part = db["parts"][args.part]
    board = bm["boards"][args.board]

    if board.get("role") == "stack_lower":
        sys.exit(f"board {args.board} carries no MCU - it is the lower half of "
                 f"a stack. Generate constraints against the upper board.")
    if not board.get("socket_to_mcu"):
        sys.exit(f"board {args.board} has no pin mapping yet "
                 f"(see its description in boardmap.yaml)")

    problems = check(args.part, part, args.board, board)
    if problems:
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        sys.exit(1)

    outdir = os.path.join(ROOT, args.out)
    os.makedirs(outdir, exist_ok=True)

    # ---- collect the assignments ----------------------------------------
    rows = []
    for pin in sorted(part["socket_pins"]):
        sig = part["socket_pins"][pin]
        if sig in ("VCC", "GND"):
            rows.append((pin, sig, "-", "-"))
            continue
        mcu = board["socket_to_mcu"][pin]
        rows.append((pin, sig, fabric_port(sig), mcu))

    # Board-local signals that land on a fabric pad, by boardmap control key.
    # The port names are fastprom_top's. Keys not listed here are not fabric
    # pads and are handled below: bank_select (image select read by firmware,
    # not by the fabric) and hse_in (the MCU's HSE clock input).
    ctrl_ports = {
        "data_oe": "buf_noe",
    }
    ctrl = [(k, v) for k, v in board["control"].items() if k in ctrl_ports]
    hse_pin = board["control"].get("hse_in")
    bank_select = board["control"].get("bank_select")

    # ---- .pcf ------------------------------------------------------------
    pcf = [f"# {args.part} on {args.board} - generated by tools/gen_pins.py",
           "# open-flow pin constraints", ""]
    for pin, sig, port, mcu in rows:
        if mcu == "-":
            continue
        pcf.append(f"set_io {port:<12} {mcu}   # socket pin {pin} ({sig})")
    pcf.append("")
    for name, mcu in ctrl:
        pcf.append(f"set_io {ctrl_ports[name]:<12} {mcu}   # board-local ({name})")
    if hse_pin:
        pcf.append(f"# {hse_pin} is OSC_IN, the HSE clock (MCU clock tree, not a fabric pad)")
    if bank_select:
        pcf.append(f"# image select: {bank_select} (read by firmware, not a fabric pad)")

    pcf_path = os.path.join(outdir, f"{args.part}.pcf")
    with open(pcf_path, "w") as fh:
        fh.write("\n".join(pcf) + "\n")

    # ---- .ve -------------------------------------------------------------
    # gen_vlog folds a one-bit bus to a scalar port (a part with one enable
    # gets "ce_pin", not "ce_pin[0]"), and then cannot match an indexed name
    # in the .ve to it: the pin is left unassigned and Supra places it
    # wherever it likes. So name one-bit buses without the index here.
    widths = {}
    for _pin, _sig, port, _mcu in rows:
        if port != "-":
            base = port.split("[")[0]
            widths[base] = widths.get(base, 0) + 1

    def ve_name(port):
        base = port.split("[")[0]
        return base if widths.get(base) == 1 else port

    ve = [f"# {args.part} on {args.board} - generated by tools/gen_pins.py",
          "# vendor Supra pin constraints",
          ""] + ve_clocks(board)
    if args.rdclk:
        # BRAM mode's read port runs on its own PLL output so it can be faster
        # than sys_clock (the CPU's AHB clock, which does not close at 200
        # MHz). 200 MHz is the most Supra allows (restricted Fmax 200.08 MHz);
        # the period is the sampling term of BRAM-mode tAA. LOGIC mode leaves
        # it unused. See docs/03-timing-budget.md.
        # Output 2: AGM's gen_vlog takes output 0 for SYSCLK, 1 for USB's
        # fixed 60 MHz whenever USB0 is enabled (silently overriding any
        # PLLCLK1, which once cut this clock to 60 MHz), 2 only for the
        # MAC, which this design does not use, 3 for BUSCLK.
        ve.append(f"PLLCLK2 {args.rdclk:g}   # BRAM read-port clock")
        ve.append("PLL_CLKOUT2 rd_clk:OUTPUT")
    if board.get("usb"):
        # USB0 is a hard block on PIN_22/23, but the fabric configuration
        # enables it and gen_vlog clocks it from PLL output 1 at 60 MHz
        # (gen_vlog's USBCLK_FREQ). Without this line the firmware's USB
        # controller has no clock.
        ve.append("USB0 device   # PIN_22/23, PLL output 1 at 60 MHz")
    ve.append("")
    for pin, sig, port, mcu in rows:
        if mcu == "-":
            continue
        direction = "OUTPUT" if sig.startswith("D") else "INPUT"
        ve.append(f"{ve_name(port):<12} {mcu}:{direction}   # socket pin {pin} ({sig})")
    ve.append("")
    for name, mcu in ctrl:
        ve.append(f"{ctrl_ports[name]:<12} {mcu}:OUTPUT")
    if bank_select == "uart_dip":
        # The MCU reaches a package pin only through the fabric's routing,
        # so the image-select switch is invisible to the firmware unless the
        # .ve wires the UART0 pins to the GPIO bits UART0's alternate
        # function uses (AgRV_pio framework-agrv_sdk/src/AltaRiscv.h:
        # UART0_UARTTXD_AF_GPIO 7 / mask 1<<6, UART0_UARTRXD_AF_GPIO 6 /
        # mask 1<<1). A plain GPIO line with no direction makes gen_vlog
        # build a bidirectional pad: the firmware reads both pins as inputs
        # first (AFSEL clear), then hands them to UART0 (AFSEL set) for the
        # boot banner. Without this the gpio inputs are tied to 0 and every
        # boot reads bank 0. See fw/fastprom-ag32/src/pins.rs.
        ve.append("")
        ve.append("GPIO7_6      PIN_20   # UART0 TXD; image-select bit 1 (SW1 switch 2)")
        ve.append("GPIO6_1      PIN_21   # UART0 RXD; image-select bit 0 (SW1 switch 1)")
    elif bank_select:
        ve.append(f"# image select: {bank_select} (read by firmware, not a fabric pad)")

    ve_path = os.path.join(outdir, f"{args.part}.ve")
    with open(ve_path, "w") as fh:
        fh.write("\n".join(ve) + "\n")

    # ---- HDL parameters ---------------------------------------------------
    ce_mask = 0
    for i, low in enumerate(part["ce_active_low"]):
        if low:
            ce_mask |= 1 << i

    vh = [
        f"// {args.part} on {args.board} - generated by tools/gen_pins.py",
        "// Parameters for fastprom_top.",
        "",
        f"localparam integer PROM_AW        = {part['address_bits']};",
        f"localparam integer DW             = {part['width']};",
        f"localparam integer NCE            = {part['ce_count']};",
        f"localparam [3:0]   CE_ACTIVE_LOW  = 4'b{ce_mask:04b};",
        f"localparam integer OPEN_COLLECTOR = {1 if args.open_collector else 0};",
        f"localparam integer BANKW          = {args.banks};",
        "",
    ]
    vh_path = os.path.join(outdir, f"{args.part}_params.vh")
    with open(vh_path, "w") as fh:
        fh.write("\n".join(vh) + "\n")

    print(f"{args.part} on {args.board}: "
          f"{part['depth']}x{part['width']}, {part['ce_count']} enable(s), "
          f"{'open-collector' if args.open_collector else 'tri-state'}, "
          f"{args.banks} bank bit(s)")
    print(f"  wrote {os.path.relpath(pcf_path, ROOT)}")
    print(f"  wrote {os.path.relpath(ve_path, ROOT)}")
    print(f"  wrote {os.path.relpath(vh_path, ROOT)}")

    if args.docs:
        write_docs(db, bm)


def write_docs(db, bm):
    L = ["# Board mapping",
         "",
         "Generated by `tools/gen_pins.py --docs`.",
         "",
         "## Why one board covers two organisations",
         "",
         "The AG32's fabric owns the I/O ring, so any fabric signal can be",
         "assigned to any user pin. That means the part-specific pinout lives",
         "entirely in the generated constraints, not in copper.",
         "",
         "What the board must commit to is *direction*, because the bus",
         "interface buffers are unidirectional. Fortunately the two mainstream",
         "organisations agree exactly on which pins are which direction:",
         "",
         "| Socket pin | 512x8 | 256x8 | 4096x4 | 2048x4 |",
         "|---:|---|---|---|---|"]

    parts = db["parts"]
    for pin in range(1, 21):
        cells = []
        for name in ("512x8", "256x8", "4096x4", "2048x4"):
            cells.append(parts[name]["socket_pins"].get(pin, "-"))
        L.append(f"| {pin} | " + " | ".join(cells) + " |")

    L += [
        "",
        "Data lines sit on pins 6-9 and 11-14 for both x8 parts, and",
        "everything else on 1-5 and 15-19. Pin 16 is the only pin that",
        "changes meaning - address A5 on the 512x8, a second active-low",
        "enable on the 256x8 - and both are inputs, so the same receive",
        "buffer serves either.",
        "",
        "The survey of these parts warns that confusing the two frames",
        "shorts an address line to an enable. Here it cannot: pin 16 always",
        "arrives at a buffer input and is only ever *interpreted* by the",
        "fabric.",
        "",
        "The 4096x4 and Harris 2048x4 frames move data lines into the input",
        "group, so they would need a lower board with direction-switchable",
        "buffers on pins 6-9. They are in the database, and",
        "`tools/gen_pins.py` refuses to generate constraints for them against",
        "a board that cannot support them rather than emitting something",
        "that would drive a host's address line.",
        "",
        "## Boards",
        "",
    ]

    for bname, board in bm["boards"].items():
        L += [f"### {bname}", "", board["description"].strip(), ""]
        # The lower half of a stack carries no microcontroller at all - only
        # the pins, the board-to-board connector and the socket-side pulls.
        if "mcu" in board:
            L.append(f"* MCU: {board['mcu']} ({board['package']})")
        else:
            L.append("* No MCU: lower half of a two-board stack")
        L += [f"* Supports: {', '.join(board['supports'])}", ""]
        if board.get("socket_to_mcu"):
            L += ["| Socket pin | AG32 pin | Direction |", "|---:|---|---|"]
            for pin in range(1, 21):
                if pin in board["socket_to_mcu"]:
                    d = "output" if pin in board["output_group"] else "input"
                    L.append(f"| {pin} | {board['socket_to_mcu'][pin]} | {d} |")
                elif pin == board["power"]["vcc"]:
                    L.append(f"| {pin} | - | VCC (5 V in) |")
                elif pin == board["power"]["gnd"]:
                    L.append(f"| {pin} | - | GND |")
            L.append("")
            if board.get("control"):
                L += ["Board-local signals:", "",
                      "| Signal | AG32 pin |", "|---|---|"]
                for k, v in board["control"].items():
                    L.append(f"| {k} | {v} |")
                L.append("")
            if board.get("reserved"):
                L += ["Pins deliberately left alone:", "",
                      "| AG32 pin | Reason |", "|---|---|"]
                for k, v in board["reserved"].items():
                    L.append(f"| {k} | {str(v).strip()} |")
                L.append("")
        elif board.get("role") == "stack_lower":
            L += ["No AG32 pin map here: each socket line passes through this",
                  "board's buffers and the board-to-board connector (contact",
                  "allocation: `stack_contacts()` in `tools/gen_kicad.py`,",
                  "checked by `make stack`) to the upper board's AG32, mapped",
                  "below.", ""]
        else:
            L += ["No pin mapping yet.", ""]

    path = os.path.join(ROOT, "docs", "04-board-mapping.md")
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("  wrote docs/04-board-mapping.md")


if __name__ == "__main__":
    main()
