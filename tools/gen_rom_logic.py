#!/usr/bin/env python3
"""Emit a ROM image as an explicit-case Verilog module for LOGIC mode.

LOGIC mode implements the PROM contents as a boolean function of the address
in the fabric's LUT4s, which is what makes an asynchronous read with no clock
and no memory block possible. An explicit case statement is used rather than
an initialised array so the synthesiser is unambiguously given combinational
logic to minimise, with no chance of it reaching for a synchronous RAM block.

The generated module is interface-compatible with hdl/fastprom_rom_logic.v
(the reference model), so a build substitutes one for the other and
sim/tb_equiv.v proves they agree on every address.
"""
import argparse
import os
import sys


def read_image(path, width):
    """Read a .hex (one word per line) or .bin image into a list of ints."""
    if path.endswith(".bin"):
        with open(path, "rb") as fh:
            words = list(fh.read())
        if width == 4:
            words = [w & 0xF for w in words]
        return words

    words = []
    with open(path) as fh:
        for lineno, raw in enumerate(fh, 1):
            line = raw.split("//")[0].strip()
            if not line:
                continue
            for tok in line.split():
                try:
                    words.append(int(tok, 16))
                except ValueError:
                    sys.exit(f"{path}:{lineno}: not a hex word: {tok!r}")
    return words


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--image", required=True, help="ROM contents (.hex or .bin)")
    ap.add_argument("--aw", type=int, required=True,
                    help="total address width, including bank-select bits")
    ap.add_argument("--dw", type=int, default=8)
    ap.add_argument("--module", default="fastprom_rom_logic")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    depth = 1 << args.aw
    mask = (1 << args.dw) - 1
    words = read_image(args.image, args.dw)

    if len(words) > depth:
        sys.exit(f"image has {len(words)} words but AW={args.aw} holds only {depth}")
    if any(w > mask for w in words):
        sys.exit(f"image contains a word wider than DW={args.dw}")

    # Unprogrammed bipolar PROM cells read as 1s. Padding with 1s keeps a
    # short image behaving like a partly-programmed real part, and lets the
    # synthesiser fold the whole unused region into the default arm.
    pad = depth - len(words)
    digits = (args.dw + 3) // 4

    # Emitting the most common word as `default` rather than as thousands of
    # explicit arms is a large win for structured images, where one value can
    # dominate: the synthesiser then only has to build logic for the
    # exceptions.
    counts = {}
    for w in words:
        counts[w] = counts.get(w, 0) + 1
    if pad:
        counts[mask] = counts.get(mask, 0) + pad
    default_word = max(counts, key=lambda w: (counts[w], -w))

    lines = [
        "// Generated by tools/gen_rom_logic.py -- do not edit.",
        f"//   image     {os.path.basename(args.image)}",
        f"//   organisation {depth}x{args.dw} (AW={args.aw})",
        f"//   distinct words {len(counts)}, default arm 0x{default_word:0{digits}x}"
        f" covers {counts[default_word]} of {depth} locations",
        "`default_nettype none",
        "",
        f"module {args.module} #(",
        f"    parameter integer AW = {args.aw},",
        f"    parameter integer DW = {args.dw},",
        '    parameter         INIT_HEX = ""   // unused: contents are in the bitstream',
        ") (",
        "    input  wire [AW-1:0] a,",
        "    output wire [DW-1:0] d",
        ");",
        f"    localparam integer GEN_AW = {args.aw};",
        f"    localparam integer GEN_DW = {args.dw};",
        "",
        "`ifndef YOSYS",
        "    initial begin",
        "        if (AW != GEN_AW || DW != GEN_DW)",
        '            $fatal(1, "%m: generated for AW=%0d DW=%0d but instantiated as AW=%0d DW=%0d",',
        "                   GEN_AW, GEN_DW, AW, DW);",
        "    end",
        "`endif",
        "",
        # A function body inside a continuous assignment, rather than an
        # `always @*` block: an always block does not execute until one of its
        # inputs changes, so at time zero in simulation the outputs would read
        # X until the host happened to move the address. A continuous
        # assignment evaluates immediately and synthesises identically.
        "    function [DW-1:0] rom_lookup;",
        "        input [AW-1:0] addr;",
        "        case (addr)",
    ]

    for addr, word in enumerate(words):
        if word == default_word:
            continue
        lines.append(
            f"            {args.aw}'d{addr}: rom_lookup = {args.dw}'h{word:0{digits}x};")

    lines += [
        f"            default: rom_lookup = {args.dw}'h{default_word:0{digits}x};",
        "        endcase",
        "    endfunction",
        "",
        "    assign d = rom_lookup(a);",
        "",
        "endmodule",
        "",
        "`default_nettype wire",
    ]

    with open(args.out, "w") as fh:
        fh.write("\n".join(lines) + "\n")

    explicit = sum(1 for w in words if w != default_word)
    print(f"{args.out}: {depth}x{args.dw}, {len(counts)} distinct words, "
          f"{explicit} explicit case arms, default 0x{default_word:0{digits}x}")


if __name__ == "__main__":
    main()
