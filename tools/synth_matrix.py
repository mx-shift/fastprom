#!/usr/bin/env python3
"""Measure fabric cost of LOGIC mode across organisations and content types.

LOGIC mode puts the PROM contents in LUT4s, so whether a given part fits the
AGRV2K fabric depends on two things: how many bits it holds, and how
compressible those bits are. This sweeps both and writes a markdown table.

Prefers a yosys built with ABC (proper structural LUT mapping). Falls back to
an ABC-free gate2lut flow, which still bounds the cost from above but is
noticeably pessimistic - the fallback is labelled as such in the output.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys

# The only organisations that ever shipped in a 20-pin bipolar DIP. Several
# parts commonly assumed to be 20-pin are not: 82S137 (1024x4), 82S185 and
# 63S841 (2048x4) and MB7128 are 18-pin, and 74S474/475 are 24-pin.
#
# (label, address width, data width, representative parts)
ORGS = [
    ("256x8",        8,  8, "82S135, 74S471, 63S281, 6309, MB7118"),
    ("512x8",        9,  8, "82S147, 74S472, 6349, 63S481, HM-7649, MB7124"),
    ("2048x4",      11,  4, "HM-7686/7687 (Harris only)"),
    ("4096x4",      12,  4, "82S195, 63S1641, Am27S41 (different pin frame)"),
    ("512x8 x2 img", 10, 8, "two selectable 512x8 images"),
    ("512x8 x4 img", 11, 8, "four selectable 512x8 images"),
]

KINDS = ["decode", "palette", "random"]

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def find_yosys():
    for name in ("yosys", "yowasp-yosys"):
        path = shutil.which(name)
        if path:
            return path, (name == "yosys")
    sys.exit("no yosys found on PATH")


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def synth(yosys, has_abc, src, top, build):
    stat = os.path.join(build, "stat.txt")
    ltp = os.path.join(build, "ltp.txt")
    if has_abc:
        script = f"""
read_verilog {src}
synth -top {top} -lut 4
tee -o {stat} stat
tee -o {ltp} ltp -noff
"""
    else:
        # No ABC: map gates to LUTs directly and let opt_lut merge them.
        script = f"""
read_verilog {src}
hierarchy -top {top}
proc
opt -full
memory_map
opt -full
techmap
opt -full
simplemap
techmap -map +/gate2lut.v -D LUT_WIDTH=4
opt_lut
clean
tee -o {stat} stat
tee -o {ltp} ltp -noff
"""
    ys = os.path.join(build, "synth.ys")
    with open(ys, "w") as fh:
        fh.write(script)

    proc = run([yosys, "-q", "-s", ys], cwd=ROOT)
    if proc.returncode != 0:
        print(proc.stderr[-2000:], file=sys.stderr)
        sys.exit(f"yosys failed on {src}")

    luts = None
    with open(stat) as fh:
        for line in fh:
            m = re.search(r"(\d+)\s+\$lut\b", line)
            if m:
                luts = int(m.group(1))
    depth = None
    with open(ltp) as fh:
        for line in fh:
            m = re.search(r"length=(\d+)", line)
            if m:
                depth = int(m.group(1))
    return luts, depth


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fabric-les", type=int, default=2048,
                    help="usable logic elements in the fabric")
    ap.add_argument("--out", default="docs/synth-results.md")
    args = ap.parse_args()

    yosys, has_abc = find_yosys()
    build = os.path.join(ROOT, "build", "matrix")
    os.makedirs(build, exist_ok=True)

    print(f"yosys: {yosys} (ABC {'available' if has_abc else 'NOT available'})")

    rows = []
    for label, aw, dw, parts in ORGS:
        depth_words = 1 << aw
        bits = depth_words * dw
        for kind in KINDS:
            img = os.path.join(build, f"img_{aw}_{dw}_{kind}.hex")
            run([sys.executable, os.path.join(ROOT, "tools", "mkimage.py"),
                 "--kind", kind, "--depth", str(depth_words),
                 "--width", str(dw), "--out", img], cwd=ROOT)

            src = os.path.join(build, f"rom_{aw}_{dw}_{kind}.v")
            r = run([sys.executable, os.path.join(ROOT, "tools", "gen_rom_logic.py"),
                     "--image", img, "--aw", str(aw), "--dw", str(dw),
                     "--out", src], cwd=ROOT)
            if r.returncode != 0:
                sys.exit(r.stderr)

            luts, dep = synth(yosys, has_abc, src, "fastprom_rom_logic", build)
            fits = "yes" if luts is not None and luts <= args.fabric_les else "NO"
            rows.append((label, bits, kind, luts, dep, fits, parts))
            print(f"  {label:<14} {kind:<8} {luts:>6} LUT4  depth {dep}  fits={fits}")

    lines = [
        "# LOGIC-mode fabric cost",
        "",
        f"Generated by `tools/synth_matrix.py`. Mapper: "
        f"{'yosys + ABC (structural LUT mapping)' if has_abc else 'yosys gate2lut + opt_lut, NO ABC - counts are an upper bound and pessimistic'}.",
        f"Fabric budget assumed: {args.fabric_les} LUT4-equivalent logic elements.",
        "",
        "`depth` is the longest topological path in LUT4 levels, which is what",
        "sets the combinational delay through the ROM.",
        "",
        "| Organisation | Bits | Content | LUT4 | Depth | Fits | Representative parts |",
        "|---|---:|---|---:|---:|---|---|",
    ]
    for label, bits, kind, luts, dep, fits, parts in rows:
        lines.append(f"| {label} | {bits} | {kind} | {luts} | {dep} | {fits} | {parts} |")

    lines += [
        "",
        "## Reading this",
        "",
        "* `decode` and `palette` contents collapse to a handful of LUT4s. Most",
        "  real 20-pin PROMs hold exactly this kind of structured data - colour",
        "  palettes, address decodes, state-machine next-state tables - so the",
        "  typical case is nowhere near the fabric limit.",
        "* `random` is the incompressible worst case and stands in for character",
        "  generators and microcode, where the contents have little structure.",
        "  This is the column that decides whether a part fits.",
        "* Multi-image builds multiply the bit count.",
        "* BRAM mode is the shipped mode. LOGIC mode is the fallback where BRAM",
        "  mode's extra delay misses a grade's timing (`03-timing-budget.md`),",
        "  and only for contents that fit.",
    ]

    out = os.path.join(ROOT, args.out)
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
