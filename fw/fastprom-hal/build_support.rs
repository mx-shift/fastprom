// What the board binaries' build.rs do, included by each: write memory.x
// from fastprom-core's memmap.rs (the one source of the flash map), and
// build_info.rs with the firmware version (Cargo's) and the board revision
// (hw/REVISION, as scripts/release_hw.sh reads it: whitespace stripped).
//
// Not part of the fastprom-hal crate: build scripts are std and cannot
// depend on it, so this file is include!d, as memmap.rs is.

use std::{env, fs, path::PathBuf};

include!("../fastprom-core/src/memmap.rs");

/// Room for the DFU stage's boot check at the reset vector: one page.
const DFU_BOOT_LEN: u32 = PAGE;

/// Which binary is being linked.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Binary {
    /// fastprom-dfu, at the reset vector.
    Dfu,
    /// fastprom-ag32, behind its header.
    Application,
    /// fastprom-recovery, the recovery loader: all in SRAM, uploaded there
    /// through the mask ROM.
    Recovery,
}

/// Write memory.x and build_info.rs into OUT_DIR, and link with riscv-rt's
/// link.x.
pub fn build(binary: Binary) {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets it"));
    let revision = manifest.join("../../hw/REVISION");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../fastprom-hal/build_support.rs");
    println!("cargo:rerun-if-changed=../fastprom-core/src/memmap.rs");
    println!("cargo:rerun-if-changed={}", revision.display());

    let out = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    fs::write(out.join("memory.x"), memory_x(binary)).expect("writing memory.x");
    fs::write(out.join("build_info.rs"), build_info(&revision)).expect("writing build_info.rs");
    println!("cargo:rustc-link-search={}", out.display());
    if env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("riscv32") {
        println!("cargo:rustc-link-arg-bins=-Tlink.x");
    }
}

/// The recovery loader's entry stub ahead of riscv-rt's `.text`: `fence.i`,
/// then a jump to `_start` (fastprom-recovery main.rs), uncompressed.
const RECOVERY_STUB_LEN: u32 = 8;

/// The recovery loader's memory.x: its header and code in the upload window
/// at RECOVERY_BASE, its .data, .bss and stack at the bottom of SRAM.
fn recovery_memory_x() -> String {
    let stub = RECOVERY_ENTRY;
    let text = RECOVERY_ENTRY + RECOVERY_STUB_LEN;
    let text_len = RECOVERY_BASE + RECOVERY_LEN - text;
    format!(
        "/* Generated by fw/fastprom-hal/build_support.rs from
   fw/fastprom-core/src/memmap.rs: edit that. */
MEMORY
{{
  LHEADER (r)  : ORIGIN = {RECOVERY_BASE:#010x}, LENGTH = {RECOVERY_HEADER_LEN:#x}
  LENTRY (rx)  : ORIGIN = {stub:#010x}, LENGTH = {RECOVERY_STUB_LEN:#x}
  LOADER (rwx) : ORIGIN = {text:#010x}, LENGTH = {text_len:#x}
  RAM   (rw)   : ORIGIN = {RECOVERY_RAM_BASE:#010x}, LENGTH = {RECOVERY_RAM_LEN:#x}
}}
REGION_ALIAS(\"REGION_TEXT\", LOADER);
REGION_ALIAS(\"REGION_RODATA\", LOADER);
REGION_ALIAS(\"REGION_DATA\", RAM);
REGION_ALIAS(\"REGION_BSS\", RAM);
REGION_ALIAS(\"REGION_HEAP\", RAM);
REGION_ALIAS(\"REGION_STACK\", RAM);

SECTIONS
{{
  /DISCARD/ : {{ *(.eh_frame) *(.eh_frame_hdr) }}
}}

/* The loader's header (fastprom-core recovery LoaderHeader), stamped after
   linking by tools/fw_stamp.py loader, and the entry stub GO lands on. */
SECTIONS
{{
  .fastprom_loader_header ORIGIN(LHEADER) : {{ KEEP(*(.fastprom_loader_header)) }} > LHEADER
  .fastprom_loader_entry ORIGIN(LENTRY) : {{ KEEP(*(.fastprom_loader_entry)) }} > LENTRY
}}
ENTRY(__fastprom_loader_entry)

SECTIONS
{{
  .init.rust : ALIGN(4) {{ KEEP(*(.init.rust)) }} > LOADER
}} INSERT AFTER .text;

/* fastprom-hal flash.rs's SRAM routines: already in SRAM, run in place
   (Ag32Flash::init's copy is onto themselves). */
SECTIONS
{{
  .ramfunc : ALIGN(4)
  {{
    __sramfunc = .;
    *(.ramfunc .ramfunc.*);
    . = ALIGN(4);
    __eramfunc = .;
  }} > LOADER
}} INSERT AFTER .rodata;
__siramfunc = LOADADDR(.ramfunc);

/* Not linked into, recorded in the ELF for tools/fw_layout.py. */
__fastprom_image_start = {RECOVERY_BASE:#010x};
__fastprom_image_end = {image_end:#010x};
__fastprom_entry = {RECOVERY_ENTRY:#010x};
__fastprom_ram_start = {RECOVERY_RAM_BASE:#010x};
__fastprom_ram_end = {ram_end:#010x};
",
        image_end = RECOVERY_BASE + RECOVERY_LEN,
        ram_end = RECOVERY_RAM_BASE + RECOVERY_RAM_LEN,
    )
}

fn memory_x(binary: Binary) -> String {
    // Where the code proper starts, after the leading region.
    let (base, len, text) = match binary {
        Binary::Dfu => (DFU_BASE, DFU_LEN, DFU_BASE + DFU_BOOT_LEN),
        Binary::Application => (APP_BASE, APP_LEN, APP_ENTRY),
        Binary::Recovery => return recovery_memory_x(),
    };
    // The address the binary is entered at: the reset vector, or where the
    // DFU stage jumps.
    let entry = match binary {
        Binary::Dfu => DFU_BASE,
        Binary::Application | Binary::Recovery => APP_ENTRY,
    };
    // Ahead of riscv-rt's .text, in a region of its own: the application's
    // header, or the DFU stage's boot check at the reset vector.
    let (header_region, header_section) = match binary {
        Binary::Dfu => (
            format!("  BOOT (rx)   : ORIGIN = {DFU_BASE:#010x}, LENGTH = {DFU_BOOT_LEN:#x}\n"),
            "/* The DFU stage's boot check (fastprom-dfu boot.rs): the first code at
   the reset vector, and the ELF's entry. */
SECTIONS
{
  .fastprom_reset ORIGIN(BOOT) : { KEEP(*(.fastprom_reset)) } > BOOT
}
ENTRY(__fastprom_reset)
"
            .to_string(),
        ),
        Binary::Application | Binary::Recovery => (
            format!(
                "  HEADER (r)  : ORIGIN = {APP_BASE:#010x}, LENGTH = {APP_HEADER_LEN:#x}\n"
            ),
            "/* The application header (fastprom-core header.rs), stamped after linking
   by tools/fw_stamp.py. */
SECTIONS
{
  .fastprom_header ORIGIN(HEADER) : { KEEP(*(.fastprom_header)) } > HEADER
}
"
            .to_string(),
        ),
    };
    let text_len = base + len - text;
    format!(
        "/* Generated by fw/fastprom-hal/build_support.rs from
   fw/fastprom-core/src/memmap.rs: edit that. */
MEMORY
{{
{header_region}  FLASH (rx)  : ORIGIN = {text:#010x}, LENGTH = {text_len:#x}
  RAM   (rwx) : ORIGIN = {SRAM_BASE:#010x}, LENGTH = {SRAM_SIZE:#x}
}}
REGION_ALIAS(\"REGION_TEXT\", FLASH);
REGION_ALIAS(\"REGION_RODATA\", FLASH);
REGION_ALIAS(\"REGION_DATA\", RAM);
REGION_ALIAS(\"REGION_BSS\", RAM);
REGION_ALIAS(\"REGION_HEAP\", RAM);
REGION_ALIAS(\"REGION_STACK\", RAM);

/* panic = abort: unwind tables are never read, so keep them out of flash. */
SECTIONS
{{
  /DISCARD/ : {{ *(.eh_frame) *(.eh_frame_hdr) }}
}}
{header_section}
/* riscv-rt's _start_rust: placed with the code, which the linker's orphan
   placement would not do now that executable code also lives in RAM. */
SECTIONS
{{
  .init.rust : ALIGN(4) {{ KEEP(*(.init.rust)) }} > FLASH
}} INSERT AFTER .text;

/* Code that must run from SRAM (fastprom-hal flash.rs): loaded from flash
   after .data, copied by Ag32Flash::init, not by the startup code, so it
   costs nothing until the flash is written. */
SECTIONS
{{
  .ramfunc : ALIGN(4)
  {{
    __sramfunc = .;
    *(.ramfunc .ramfunc.*);
    . = ALIGN(4);
    __eramfunc = .;
  }} > RAM AT > FLASH
}} INSERT AFTER .uninit;
__siramfunc = LOADADDR(.ramfunc);

/* Not linked into, recorded in the ELF for tools/fw_layout.py. */
__fastprom_image_start = {base:#010x};
__fastprom_image_end = {image_end:#010x};
__fastprom_entry = {entry:#010x};
__fastprom_dfu_start = {DFU_BASE:#010x};
__fastprom_dfu_end = {dfu_end:#010x};
__fastprom_app_start = {APP_BASE:#010x};
__fastprom_app_end = {app_end:#010x};
__fastprom_fabric_start = {FABRIC_BASE:#010x};
__fastprom_fabric_end = {fabric_end:#010x};
__fastprom_manifest_start = {MANIFEST_BASE:#010x};
__fastprom_manifest_end = {manifest_end:#010x};
__fastprom_table_start = {TABLE_BASE:#010x};
__fastprom_table_end = {table_end:#010x};
__fastprom_flash_end = {flash_end:#010x};
__fastprom_option_start = {OPTION_BASE:#010x};
__fastprom_option_end = {option_end:#010x};
__fastprom_sector = {SECTOR:#x};
__fastprom_page = {PAGE:#x};
",
        image_end = base + len,
        dfu_end = DFU_BASE + DFU_LEN,
        app_end = APP_BASE + APP_LEN,
        fabric_end = FABRIC_BASE + FABRIC_LEN,
        manifest_end = MANIFEST_BASE + MANIFEST_LEN,
        table_end = TABLE_BASE + TABLE_LEN,
        flash_end = FLASH_BASE + FLASH_SIZE,
        option_end = OPTION_BASE + OPTION_LEN,
    )
}

fn build_info(revision: &std::path::Path) -> String {
    let rev: String = fs::read_to_string(revision)
        .expect("reading hw/REVISION")
        .split_whitespace()
        .collect();
    assert!(
        !rev.is_empty() && rev.len() <= 8 && rev.bytes().all(|b| b.is_ascii_graphic()),
        "hw/REVISION {rev:?}: 1 to 8 printable characters (the header's board revision field)"
    );
    let part = |name: &str| -> u16 {
        env::var(name)
            .expect("cargo sets CARGO_PKG_VERSION_*")
            .parse()
            .expect("a version number that fits the header's u16")
    };
    format!(
        "// Generated by fw/fastprom-hal/build_support.rs.
/// This firmware's version: fw/Cargo.toml's.
pub const FW_VERSION: fastprom_core::header::Version = fastprom_core::header::Version {{
    major: {},
    minor: {},
    patch: {},
}};
/// The board revision it is built for: hw/REVISION.
pub const BOARD_REV: fastprom_core::header::BoardRev =
    match fastprom_core::header::BoardRev::new({rev:?}) {{
        Some(r) => r,
        None => panic!(\"hw/REVISION is not a board revision\"),
    }};
",
        part("CARGO_PKG_VERSION_MAJOR"),
        part("CARGO_PKG_VERSION_MINOR"),
        part("CARGO_PKG_VERSION_PATCH"),
    )
}
