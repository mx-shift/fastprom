#!/usr/bin/env python3
"""Generate CRC test vectors for the firmware from Python's zlib.

The firmware must agree exactly with tools/mkimagetable.py on the CRC, or it
rejects every image at boot and the socket stays dead. Generating the expected
values here means the C test compares two independent implementations rather
than a function against itself.
"""
import os
import random
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    rng = random.Random(20260912)
    cases = [
        ("empty", b""),
        ("one_zero", b"\x00"),
        ("one_ff", b"\xff"),
        ("ascii", b"FastPROM"),
    ]
    for n in (16, 256, 512, 2048):
        cases.append((f"rand{n}", bytes(rng.getrandbits(8) for _ in range(n))))
    # An unprogrammed bipolar PROM reads as all ones, so this is the image a
    # blank part would present and is worth having as a vector.
    cases.append(("all_ff_512", b"\xff" * 512))

    out = ["/* Generated by fw/test/gen_vectors.py -- do not edit. */",
           "#ifndef VECTORS_H", "#define VECTORS_H", "",
           "#include <stdint.h>", "",
           "typedef struct { const char *name; const uint8_t *data;",
           "                 uint32_t len; uint32_t expect; } crc_vector_t;",
           ""]
    for name, data in cases:
        arr = ", ".join(f"0x{b:02x}" for b in data) or "0"
        out.append(f"static const uint8_t v_{name}[] = {{{arr}}};")
    out += ["", f"#define N_CRC_VECTORS {len(cases)}",
            "static const crc_vector_t crc_vectors[N_CRC_VECTORS] = {"]
    for name, data in cases:
        out.append(f'    {{"{name}", v_{name}, {len(data)}u, '
                   f"0x{zlib.crc32(data) & 0xFFFFFFFF:08x}u}},")
    out += ["};", "", "#endif"]

    path = os.path.join(HERE, "vectors.h")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"{path}: {len(cases)} vectors from zlib.crc32")


if __name__ == "__main__":
    main()
